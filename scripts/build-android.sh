#!/usr/bin/env bash
#
# Build Mycelium FFI library for Android targets.
#
# Prerequisites:
#   1. Android NDK installed (set ANDROID_NDK_HOME or NDK_HOME)
#   2. Rust targets installed:
#      rustup target add aarch64-linux-android armv7-linux-androideabi x86_64-linux-android
#
# Usage:
#   ./scripts/build-android.sh [--release]
#
# Output:
#   target/<arch>/release/libmycelium_ffi.so  (one per ABI)
#   android-libs/arm64-v8a/libmycelium_ffi.so
#   android-libs/armeabi-v7a/libmycelium_ffi.so
#   android-libs/x86_64/libmycelium_ffi.so

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"

# Use Command Line Tools SDK when Xcode license is not accepted
export SDKROOT="${SDKROOT:-/Library/Developer/CommandLineTools/SDKs/MacOSX.sdk}"
export DEVELOPER_DIR="${DEVELOPER_DIR:-/Library/Developer/CommandLineTools}"

# Ensure rustup-managed toolchain is on PATH (ahead of Homebrew).
# When Homebrew rustc is on PATH, it won't have cross-compilation targets.
RUSTUP_TOOLCHAIN_BIN="$(rustup which cargo 2>/dev/null | xargs dirname 2>/dev/null || true)"
if [[ -n "$RUSTUP_TOOLCHAIN_BIN" && -d "$RUSTUP_TOOLCHAIN_BIN" ]]; then
    export PATH="$RUSTUP_TOOLCHAIN_BIN:$PATH"
elif [[ -d "$HOME/.cargo/bin" ]]; then
    export PATH="$HOME/.cargo/bin:$PATH"
fi

# --- Config ---
MIN_API_LEVEL="${ANDROID_MIN_API:-21}"
PROFILE="debug"
PROFILE_DIR="debug"

if [[ "${1:-}" == "--release" ]]; then
    PROFILE="release"
    PROFILE_DIR="release"
fi

# --- Find NDK ---
NDK_HOME="${ANDROID_NDK_HOME:-${NDK_HOME:-}}"
if [[ -z "$NDK_HOME" ]]; then
    # Try common locations
    for candidate in \
        "$HOME/Library/Android/sdk/ndk"/* \
        "$HOME/Android/Sdk/ndk"/* \
        /opt/android-ndk-*; do
        if [[ -d "$candidate" ]]; then
            NDK_HOME="$candidate"
            break
        fi
    done
fi

if [[ -z "$NDK_HOME" || ! -d "$NDK_HOME" ]]; then
    echo "ERROR: Android NDK not found."
    echo "Set ANDROID_NDK_HOME or install via Android Studio SDK Manager."
    exit 1
fi

echo "Using NDK: $NDK_HOME"
echo "Min API level: $MIN_API_LEVEL"
echo "Profile: $PROFILE"

# --- Find toolchain ---
HOST_TAG=""
case "$(uname -s)" in
    Darwin) HOST_TAG="darwin-x86_64" ;;
    Linux)  HOST_TAG="linux-x86_64" ;;
    *)      echo "Unsupported host OS"; exit 1 ;;
esac

TOOLCHAIN="$NDK_HOME/toolchains/llvm/prebuilt/$HOST_TAG"
if [[ ! -d "$TOOLCHAIN" ]]; then
    echo "ERROR: NDK toolchain not found at $TOOLCHAIN"
    exit 1
fi

# --- Targets ---
declare -A TARGETS=(
    ["aarch64-linux-android"]="arm64-v8a"
    ["armv7-linux-androideabi"]="armeabi-v7a"
    ["x86_64-linux-android"]="x86_64"
)

# --- Create .cargo/config.toml for linker settings ---
CARGO_CONFIG="$PROJECT_ROOT/.cargo/config.toml"
mkdir -p "$PROJECT_ROOT/.cargo"

cat > "$CARGO_CONFIG" << EOF
# Auto-generated by build-android.sh — do not edit manually.

[target.aarch64-linux-android]
linker = "$TOOLCHAIN/bin/aarch64-linux-android${MIN_API_LEVEL}-clang"

[target.armv7-linux-androideabi]
linker = "$TOOLCHAIN/bin/armv7a-linux-androideabi${MIN_API_LEVEL}-clang"

[target.x86_64-linux-android]
linker = "$TOOLCHAIN/bin/x86_64-linux-android${MIN_API_LEVEL}-clang"
EOF

echo "Generated $CARGO_CONFIG"

# --- Build each target ---
cd "$PROJECT_ROOT"

BUILD_FLAGS="-p mycelium-ffi"
if [[ "$PROFILE" == "release" ]]; then
    BUILD_FLAGS="$BUILD_FLAGS --release"
fi

FAILED=0
for TARGET in "${!TARGETS[@]}"; do
    ABI="${TARGETS[$TARGET]}"
    echo ""
    echo "=== Building $TARGET ($ABI) ==="

    # Check if target is installed
    if ! rustup target list --installed | grep -q "$TARGET"; then
        echo "Installing Rust target: $TARGET"
        rustup target add "$TARGET"
    fi

    # Set CC, AR, and RANLIB for the cc-rs crate and vendored OpenSSL build.
    # NDK r23+ uses versioned clang (e.g. aarch64-linux-android21-clang).
    # Also put the NDK toolchain bin on PATH so OpenSSL's Makefile finds ranlib etc.
    export PATH="$TOOLCHAIN/bin:$PATH"

    case "$TARGET" in
        aarch64-linux-android)
            export CC_aarch64_linux_android="$TOOLCHAIN/bin/aarch64-linux-android${MIN_API_LEVEL}-clang"
            export AR_aarch64_linux_android="$TOOLCHAIN/bin/llvm-ar"
            export RANLIB_aarch64_linux_android="$TOOLCHAIN/bin/llvm-ranlib"
            ;;
        armv7-linux-androideabi)
            export CC_armv7_linux_androideabi="$TOOLCHAIN/bin/armv7a-linux-androideabi${MIN_API_LEVEL}-clang"
            export AR_armv7_linux_androideabi="$TOOLCHAIN/bin/llvm-ar"
            export RANLIB_armv7_linux_androideabi="$TOOLCHAIN/bin/llvm-ranlib"
            ;;
        x86_64-linux-android)
            export CC_x86_64_linux_android="$TOOLCHAIN/bin/x86_64-linux-android${MIN_API_LEVEL}-clang"
            export AR_x86_64_linux_android="$TOOLCHAIN/bin/llvm-ar"
            export RANLIB_x86_64_linux_android="$TOOLCHAIN/bin/llvm-ranlib"
            ;;
    esac

    if cargo build $BUILD_FLAGS --target "$TARGET" 2>&1; then
        # Copy to android-libs directory
        OUT_DIR="$PROJECT_ROOT/android-libs/$ABI"
        mkdir -p "$OUT_DIR"
        cp "$PROJECT_ROOT/target/$TARGET/$PROFILE_DIR/libmycelium_ffi.so" "$OUT_DIR/"
        echo "  -> $OUT_DIR/libmycelium_ffi.so"
    else
        echo "  FAILED: $TARGET"
        FAILED=$((FAILED + 1))
    fi
done

# Copy header file
HEADER_DIR="$PROJECT_ROOT/android-libs/include"
mkdir -p "$HEADER_DIR"
cp "$PROJECT_ROOT/crates/mycelium-ffi/include/mycelium.h" "$HEADER_DIR/"
echo ""
echo "  -> $HEADER_DIR/mycelium.h"

echo ""
if [[ $FAILED -eq 0 ]]; then
    echo "All targets built successfully."
    echo "Output: $PROJECT_ROOT/android-libs/"
else
    echo "WARNING: $FAILED target(s) failed to build."
    exit 1
fi
